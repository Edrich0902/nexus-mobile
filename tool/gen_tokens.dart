// Generates lib/design/tokens.g.dart from tool/tokens.json.
//
//   (cd ../nexus-web && npm run tokens:export)
//   dart run tool/gen_tokens.dart
//
// tokens.json is exported from nexus-web/src/design/tokens.ts, which stays the
// single source of truth for colour, type, space, radius and motion.
// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

void main() {
  final json = jsonDecode(File('tool/tokens.json').readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from nexus-web tokens.')
    ..writeln('// Do not edit by hand.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln()
    ..writeln("import 'package:flutter/animation.dart';")
    ..writeln()
    ..writeln("import 'package:nexus_mobile/design/ambient_palette.dart';")
    ..writeln();

  String color(String hex) {
    final h = hex.replaceFirst('#', '').toUpperCase();
    return 'Color(0xFF$h)';
  }

  String ambient(Map<String, dynamic> a) =>
      'Ambient(amb: ${color(a['amb'] as String)}, '
      'amb2: ${color(a['amb2'] as String)}, '
      'acc: ${color(a['acc'] as String)}, '
      'ink: ${color(a['ink'] as String)})';

  String ident(String key) {
    final parts = key.split(RegExp('[-_]'));
    return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  }

  final brand = json['brand'] as Map<String, dynamic>;
  out.writeln('abstract final class NxBrand {');
  brand.forEach((k, v) {
    out.writeln('  static const $k = ${color(v as String)};');
  });
  out
    ..writeln('}')
    ..writeln();

  final sections = json['sections'] as Map<String, dynamic>;
  out.writeln('enum SectionKey {');
  for (final entry in sections.entries) {
    final s = entry.value as Map<String, dynamic>;
    final field = s['field'] as Map<String, dynamic>;
    out.writeln(
      "  ${ident(entry.key)}('${entry.key}', '${s['label']}', "
      '${ambient(s['ambient'] as Map<String, dynamic>)}, '
      'FieldColour(bg: ${color(field['bg'] as String)}, '
      'ink: ${color(field['ink'] as String)})),',
    );
  }
  out
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const SectionKey(this.key, this.label, this.ambient, this.field);')
    ..writeln('  final String key;')
    ..writeln('  final String label;')
    ..writeln('  final Ambient ambient;')
    ..writeln('  final FieldColour field;')
    ..writeln('}')
    ..writeln();

  final moments = json['moments'] as Map<String, dynamic>;
  out.writeln('abstract final class NxMoments {');
  moments.forEach((k, v) {
    out.writeln('  static const $k = ${ambient(v as Map<String, dynamic>)};');
  });
  out
    ..writeln('}')
    ..writeln();

  final accents = json['accents'] as Map<String, dynamic>;
  out.writeln('abstract final class NxAccents {');
  accents.forEach((k, v) {
    if (v is String) {
      out.writeln('  static const $k = ${color(v)};');
    }
  });
  final sport = accents['sport'] as Map<String, dynamic>;
  out.writeln('  static const sport = <String, Color>{');
  sport.forEach((k, v) => out.writeln("    '$k': ${color(v as String)},"));
  out
    ..writeln('  };')
    ..writeln('}')
    ..writeln();

  final type = json['type'] as Map<String, dynamic>;
  out.writeln('abstract final class NxType {');
  type.forEach((k, v) => out.writeln('  static const double $k = $v;'));
  out
    ..writeln('}')
    ..writeln();

  final space = (json['space'] as List).cast<num>();
  out
    ..writeln('abstract final class NxSpace {')
    ..writeln('  static const scale = <double>[${space.join(', ')}];');
  for (final v in space.skip(1)) {
    out.writeln('  static const double s$v = $v;');
  }
  out
    ..writeln('}')
    ..writeln();

  final radius = json['radius'] as Map<String, dynamic>;
  out.writeln('abstract final class NxRadius {');
  radius.forEach((k, v) => out.writeln('  static const double $k = $v;'));
  out
    ..writeln('}')
    ..writeln();

  final motion = json['motion'] as Map<String, dynamic>;
  final ease = RegExp(r'cubic-bezier\(([^)]+)\)')
      .firstMatch(motion['ease'] as String)!
      .group(1)!
      .split(',')
      .map((s) => double.parse(s.trim()))
      .toList();
  out
    ..writeln('abstract final class NxMotion {')
    ..writeln('  static const ambient = Duration(milliseconds: ${motion['ambientMs']});')
    ..writeln('  static const enter = Duration(milliseconds: ${motion['enterMs']});')
    ..writeln('  static const hover = Duration(milliseconds: ${motion['hoverMs']});')
    ..writeln('  static const ease = Cubic(${ease.join(', ')});')
    ..writeln('}');

  const path = 'lib/design/tokens.g.dart';
  File(path).writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', path]);
  print('$path written');
}
